    <div class="measure">
      <h2>A worked week</h2>
      <p>This is genuinely what a week looks like using the six recipes here, and it is put
        down in this detail because meal prep advice that stops at "prep your meals" is
        useless.</p>
      <p><strong>Sunday afternoon, ninety minutes.</strong> Chickpeas in the oven, grain on the
        stovetop, both sauces blended while those run, slaw shredded and dressed, stew last in
        the big pot. Four portions of stew to the freezer. Five jars of oats made in the
        evening while the kitchen is already a mess.</p>
      <p><strong>Monday.</strong> Grain bowl: grain, chickpeas, greens, lemon tahini, seeds.
        Three minutes.</p>
      <p><strong>Tuesday.</strong> Noodles cooked fresh, peanut sauce from the jar, slaw on the
        side. Eight minutes.</p>
      <p><strong>Wednesday.</strong> Stew from the freezer, defrosted in the refrigerator since
        Tuesday morning, with bread. Ten minutes.</p>
      <p><strong>Thursday.</strong> Green shakshuka, made fresh but from the greens base, which
        is eight minutes rather than twenty-five. Slaw finished on the side.</p>
      <p><strong>Friday.</strong> Whatever you like. If the week has gone properly there is
        still grain, half a jar of each sauce and three portions of stew in the freezer, and
        Friday is not a planning problem.</p>
    </div>
