        <p class="tag">The principle</p>
        <h2>Prep components, not meals</h2>
        <p>A box containing a finished dinner is one dinner and by Wednesday you resent it.
          A container of cooked grain, a tray of roasted chickpeas and a jar of sauce are the
          same amount of work and they are four different dinners.</p>
        <p>It also fails gracefully. If the week goes wrong on Tuesday, you have not wasted
          five assembled meals; you have grain and chickpeas, which keep, and which will still
          be useful on Saturday.</p>
        <p>The whole rotation on this site is built from about seven components. Learn which
          ones keep and the planning stops being planning.</p>
      </div>
      <div class="tile tile--soft b3">
        <p class="tag">The seven components</p>
        <h2>What is worth batching</h2>
        <ul>
          <li>A pot of grain, barley or farro or brown rice</li>
          <li>A tray of roasted chickpeas</li>
          <li>Miso peanut sauce, in a jar</li>
          <li>Lemon tahini sauce, in a jar</li>
          <li>Dressed sesame slaw</li>
          <li>Sweet potato lentil stew, portioned</li>
          <li>The greens base for shakshuka</li>
        </ul>
        <p>Those seven cover most of a week and take about ninety minutes with the overlaps
          used properly.</p>
      </div>
      <div class="tile tile--apricot b3">
        <p class="tag">Not worth batching</p>
        <h2>Things to do on the night</h2>
        <ul>
          <li>Noodles. Four minutes, and they go claggy overnight.</li>
          <li>Eggs, in anything.</li>
          <li>Anything with cut avocado in it.</li>
          <li>Toasted seeds and nuts, once they are in a sauce.</li>
          <li>Dressed leaves, as distinct from dressed cabbage.</li>
        </ul>
      </div>
    </div>
