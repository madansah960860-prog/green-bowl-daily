    <div class="cols cols--2">
      <div>
        <h2>Cooling, which is the part that matters</h2>
        <p>Nearly every keeping-time failure comes from cooling badly rather than from storing
          badly. Food that sits warm in a deep container for three hours has spent three hours
          in the temperature range where bacteria multiply fastest, and no amount of
          refrigeration afterward undoes that.</p>
        <p><strong>Spread it out.</strong> Hot grain or stew on a tray cools in twenty minutes;
          the same quantity in a deep pot takes hours. This single habit adds a day or two to
          almost everything.</p>
        <p><strong>Get it into the refrigerator within two hours</strong>, and within one for
          cooked grains and rice. Do not wait for it to be completely cold; a warm container in
          a modern refrigerator is fine and is much better than the alternative.</p>
        <p><strong>Reheat once, properly.</strong> Piping hot throughout, not warm in the
          middle. Cooked rice and grains in particular should be reheated once only.</p>
        <p>None of this is fussiness. It is the difference between a keeping time of four days
          and a keeping time of two, and it costs nothing.</p>
      </div>
      <div>
        <h2>Containers, briefly</h2>
        <p>Glass, because it does not stain, does not hold smells, goes in the oven, and lets
          you see what is in it without opening it. That last one matters more than it sounds:
          things you cannot see get forgotten and thrown away.</p>
        <p>Wide and shallow rather than deep, because shallow cools faster.</p>
        <p>Jars for sauces, with lids that actually seal. A sauce in a well-sealed jar keeps
          two weeks; the same sauce in a container with a loose lid keeps five days and tastes
          of the refrigerator.</p>
        <p>You do not need a set and you do not need to buy anything. Four containers and three
          jars covers this entire site.</p>

        <h2>The one piece of kit worth buying</h2>
        <p>A mandoline, if the cabbage shredding is what stops you making the slaw. Finely
          shredded cabbage takes on dressing properly and coarse cabbage does not, and doing it
          by hand takes fifteen minutes that many people will not spend.</p>
        <p>Everything else on this site is a pot, a tray, a blender and a knife.</p>
      </div>
    </div>
  </div>
</section>

<section class="band band--tight">
