        <h2>What keeps, ranked</h2>
        <p><strong>Two weeks.</strong> The miso peanut sauce and the sesame dressing. Both are
          emulsions of fat, acid and salt, all three of which preserve, and both are better
          after a few days as the ginger and garlic mellow.</p>
        <p><strong>Three months, frozen.</strong> The sweet potato lentil stew and the greens
          base for the shakshuka. Both are cooked, both are wet, and neither contains anything
          that freezes badly.</p>
        <p><strong>Four days.</strong> Cooked grain, roasted chickpeas, dressed slaw, overnight
          oats. The working week's worth, and the reason a Sunday session covers Monday through
          Thursday rather than the whole week.</p>
        <p><strong>Same day.</strong> Anything with an egg in it, and any assembled noodle
          bowl. Both for texture reasons rather than safety ones.</p>
      </div>
      <div>
        <h2>What does not keep, and why</h2>
        <p><strong>Dressed leaves.</strong> Lettuce, arugula and spinach collapse within hours
          once salt and acid touch them. Cabbage does not, which is the entire reason the slaw
          on this site is a cabbage slaw.</p>
        <p><strong>Cooked noodles.</strong> They keep absorbing whatever they are sitting in
          and go heavy and claggy by the next day. Cook them fresh; they take four minutes.</p>
        <p><strong>Avocado, cut.</strong> Obviously. Add it at the moment of eating, which is
          why it appears in the assembly list rather than in the batch list.</p>
        <p><strong>Anything crunchy, in a sauce.</strong> Toasted seeds, nuts, fried shallots.
          All of them go soft within an hour or two. Keep them in a separate jar and add them
          at the table.</p>
      </div>
