        <h2 class="mt6">Method</h2>
        <ol class="method">
      <li><div><p>Put everything for the sauce except the water into a blender or a deep jug. Blend or use a stick blender until smooth.</p></div></li>
      <li><div><p>Add the warm water a little at a time with the motor running. You want it pourable but still thick enough to coat a spoon. It will firm up considerably in the refrigerator, so make it slightly looser than looks right.</p></div></li>
      <li><div><p>Taste it. It should be salty, sour, sweet and savory all at once, with the sourness slightly ahead. Add vinegar if it is flat and a splash more water if it is too intense.</p></div></li>
      <li><div><p>Pour into a clean jar. It keeps two weeks refrigerated and this is the part you make ahead.</p></div></li>
      <li><div><p>To build a bowl: cook the noodles, drain, and rinse under cold water for thirty seconds. Rinsing removes surface starch and stops them clumping, which matters more here than in a hot dish.</p></div></li>
      <li><div><p>Toss the noodles with three or four tablespoons of the sauce until every strand is coated. Add a splash of water if the sauce has thickened in the jar.</p></div></li>
      <li><div><p>Pile the vegetables on top rather than mixing them through, so the textures stay separate. Scatter the scallions, peanuts and herbs over.</p></div></li>
      <li><div><p>Eat cold or at room temperature. This is one of the very few things in the rotation that is genuinely better cold than warm.</p></div></li>
        </ol>

        <h2 class="mt6">Allergens</h2>
        <div class="note">
          <p>Contains peanuts, soy (miso and soy sauce) and usually wheat (noodles and most soy sauce). Use tamari and rice noodles for a gluten-free version, and tahini for a peanut-free one. Check the chilli crisp, which often contains soy and sometimes shrimp.</p>
          <p><strong>Read every label yourself.</strong> This note describes the ingredients as
            written here, not the packets in your kitchen, and formulations change without
            notice.</p>
