<aside class="prep">
  <h2>Meal prep</h2>
  <h3>Batch on Sunday</h3>
  <p>Blend a double batch of the peanut sauce and keep it in a jar. Cook the noodles fresh each time; cooked noodles in the refrigerator go claggy and no amount of sauce rescues them.</p>
  <h3>How it keeps</h3>
  <dl class="keeps">
    <div><dt>Sauce</dt><dd>14 days</dd></div>
    <div><dt>Cut veg</dt><dd>4 days</dd></div>
    <div><dt>Assembled</dt><dd>Same day</dd></div>
  </dl>
  <h3>Storage in full</h3>
  <p>Sauce: 14 days refrigerated in a sealed jar, and it thickens as it sits. Cut vegetables: 4 days in a container with a piece of paper towel in it. Assembled bowl: eat the same day; the noodles absorb the sauce and go heavy overnight.</p>
  <h3>What to swap</h3>
  <p>Tahini instead of peanut butter, for a nut-free version, using slightly less water. Sunflower seed butter also works. Any noodle: soba, rice noodles, spaghetti, or the brick of instant noodles without its flavor sachet.</p>
