        <h2 class="mt6">Method</h2>
        <ol class="method">
      <li><div><p>Heat the oil in a wide, shallow pan with a lid. Cook the onion and leek over medium heat for ten minutes until soft and sweet but not colored.</p></div></li>
      <li><div><p>Add the garlic, cumin, coriander and green chilli and cook for one minute.</p></div></li>
      <li><div><p>Add the greens in handfuls, letting each collapse before adding the next. Eight hundred grams looks impossible and will reduce to about a quarter of its volume.</p></div></li>
      <li><div><p>Add the salt and the water, cover, and cook for six to eight minutes until everything is tender. Stir once. Tougher greens like kale want the full eight; spinach needs three.</p></div></li>
      <li><div><p>Take the lid off and cook for two minutes more if there is liquid pooling in the base. You want moist rather than wet, or the eggs will poach rather than set.</p></div></li>
      <li><div><p>Squeeze in the lemon and stir through half the herbs. Taste and season. This is the point at which the base can be cooled and refrigerated for up to four days.</p></div></li>
      <li><div><p>Make eight wells in the greens with the back of a spoon and crack an egg into each. Season the eggs.</p></div></li>
      <li><div><p>Cover and cook over low heat for six to eight minutes, until the whites are set and the yolks are still soft. Check at six; residual heat carries them further after the pan comes off.</p></div></li>
      <li><div><p>Scatter the feta, the rest of the herbs and plenty of black pepper. Serve straight from the pan with yogurt and bread.</p></div></li>
        </ol>

