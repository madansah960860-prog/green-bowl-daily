<aside class="prep">
  <h2>Meal prep</h2>
  <h3>Batch on Sunday</h3>
  <p>Make a double batch of the greens base and freeze half. Then dinner is: reheat the base, crack eggs in, lid on, eight minutes.</p>
  <h3>How it keeps</h3>
  <dl class="keeps">
    <div><dt>Greens base</dt><dd>4 days</dd></div>
    <div><dt>Base, frozen</dt><dd>3 months</dd></div>
    <div><dt>With eggs</dt><dd>Same day</dd></div>
  </dl>
  <h3>Storage in full</h3>
  <p>Greens base: 4 days refrigerated, 3 months frozen in portions. Once the eggs are in, eat it; reheated egg goes rubbery and there is no way around that. Reheat the base in a pan rather than a microwave so it is hot enough to set fresh eggs.</p>
  <h3>What to swap</h3>
  <p>Any greens: chard, spinach, kale, the tops of beetroot, or a bag of frozen spinach in a hurry. Leave the feta out and it is vegan apart from the eggs; use firm tofu crumbled in instead of eggs and it is vegan entirely.</p>
