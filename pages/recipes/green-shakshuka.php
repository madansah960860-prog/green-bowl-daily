      <li><span class="qty">1</span><span>green chilli, chopped</span></li>
      <li><span class="qty">800 g<small>1 lb 12 oz</small></span><span>mixed greens, roughly chopped</span></li>
      <li><span class="qty">1 tsp</span><span>fine salt</span></li>
