<aside class="prep">
  <h2>Meal prep</h2>
  <h3>Batch on Sunday</h3>
  <p>Make the whole thing on Sunday, dressed. It is the side dish for three or four dinners and it takes twenty minutes once rather than five minutes four times.</p>
  <h3>How it keeps</h3>
  <dl class="keeps">
    <div><dt>Dressed</dt><dd>4 days</dd></div>
    <div><dt>Best on</dt><dd>Day 2 to 3</dd></div>
    <div><dt>Dressing alone</dt><dd>2 weeks</dd></div>
  </dl>
  <h3>Storage in full</h3>
  <p>Four days dressed, in a sealed container, and genuinely best on days two and three. Liquid will collect at the bottom; drain it off rather than stirring it back in. Do not freeze, for reasons that become obvious if you try.</p>
  <h3>What to swap</h3>
  <p>Any hard brassica: white cabbage, red cabbage, savoy, or a bag of shop-bought shredded slaw mix if the knife work is the obstacle. Add shredded chicken or edamame and it becomes a main course.</p>
