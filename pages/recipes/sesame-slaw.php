        <h2 class="mt6">Method</h2>
        <ol class="method">
      <li><div><p>Shred the cabbage as finely as you can manage. This is the one thing that matters: thick shreds stay tough and do not take on the dressing. A mandoline or the slicing disc of a food processor is worth using here.</p></div></li>
      <li><div><p>Toast the sesame seeds in a dry pan over medium heat for two to three minutes, shaking constantly, until they smell nutty and a few start popping. Tip them straight out of the pan; they burn in the residual heat if left.</p></div></li>
      <li><div><p>Shake all the dressing ingredients together in a jar until emulsified. Taste it on a piece of cabbage rather than off the spoon; it should be noticeably sharper than seems right on its own, because the cabbage dilutes it.</p></div></li>
      <li><div><p>Put the cabbage, carrot, pepper and scallions in your largest bowl. Pour over about two thirds of the dressing and toss thoroughly with your hands for a full minute.</p></div></li>
      <li><div><p>Leave it for twenty minutes at room temperature. The salt in the dressing draws water out of the cabbage and it softens slightly and collapses in volume.</p></div></li>
      <li><div><p>Toss again, taste, and add the remaining dressing if it needs it. Add the cilantro and most of the sesame seeds.</p></div></li>
      <li><div><p>Keep the last of the sesame seeds back and add them when you serve, on any day. They lose their crunch within a few hours in the dressing and it is a small thing that makes a noticeable difference.</p></div></li>
        </ol>

        <h2 class="mt6">Allergens</h2>
        <div class="note">
          <p>Contains sesame and soy. Contains wheat if you use standard soy sauce; tamari is the swap. Contains honey unless you use maple syrup. Free from milk, egg, nuts and fish as written.</p>
          <p><strong>Read every label yourself.</strong> This note describes the ingredients as
            written here, not the packets in your kitchen, and formulations change without
            notice.</p>
        </div>

