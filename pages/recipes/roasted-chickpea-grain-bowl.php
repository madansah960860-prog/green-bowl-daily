<aside class="prep">
  <h2>Meal prep</h2>
  <h3>Batch on Sunday</h3>
  <p>Roast a double tray of chickpeas and cook a large pot of grain on Sunday. Both keep four days. The sauce keeps a week. Then a bowl is three minutes of assembly.</p>
  <h3>How it keeps</h3>
  <dl class="keeps">
    <div><dt>Grain</dt><dd>4 days</dd></div>
    <div><dt>Chickpeas</dt><dd>4 days</dd></div>
    <div><dt>Tahini sauce</dt><dd>7 days</dd></div>
  </dl>
  <h3>Storage in full</h3>
  <p>Grain: 4 days refrigerated, spread thin to cool fast first. Chickpeas: 4 days in a container left slightly open, because sealing them traps steam and softens them completely. Sauce: 7 days, and it thickens; loosen with water.</p>
  <h3>What to swap</h3>
  <p>Any grain: farro, barley, brown rice, quinoa, freekeh. Any bean: butter beans and cannellini both roast well. Any sauce: the peanut sauce from the noodle bowl works here too, as does plain yogurt with lemon and salt.</p>
