        <h2 class="mt6">Method</h2>
        <ol class="method">
      <li><div><p>Heat the oven to 425&#176;F. Dry the chickpeas properly on a towel; wet chickpeas steam instead of crisping and this is the whole difference between a good tray and a disappointing one.</p></div></li>
      <li><div><p>Toss them with the oil, cumin, paprika and salt and spread on a large tray in one layer. Two trays is better than one crowded one.</p></div></li>
      <li><div><p>Roast for thirty to thirty-five minutes, shaking the tray twice. They should be golden and firm, with a few that have split open. They crisp further as they cool and they will soften again in the refrigerator, which is normal.</p></div></li>
      <li><div><p>While they roast, cook the grain in well-salted water according to its packet. Drain and spread it on a tray to cool quickly rather than leaving it in the pot, where it overcooks.</p></div></li>
      <li><div><p>Make the sauce: whisk the tahini, lemon juice, garlic and salt together. It will seize into a thick paste, which is alarming and correct. Then add the cold water a tablespoon at a time, whisking, and it will loosen into something silky.</p></div></li>
      <li><div><p>To build a bowl, start with the grain, add the greens and press them down so they wilt slightly against the warm grain, then the chickpeas, then the avocado and pickled onion.</p></div></li>
      <li><div><p>Spoon the sauce over rather than tossing it through, so you get a bite with sauce and a bite without. Finish with the seeds and herbs, which are the crunch slot and the one most often skipped.</p></div></li>
        </ol>

        <h2 class="mt6">Allergens</h2>
        <div class="note">
          <p>Contains sesame (tahini). Contains gluten if you use barley or farro; use brown rice or quinoa to avoid. Dukkah frequently contains nuts. Free from milk, egg, soy and fish as written.</p>
