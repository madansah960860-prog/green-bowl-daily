  <h2>Meal prep</h2>
  <h3>Batch on Sunday</h3>
  <p>Make the full six portions and freeze four. This is the thing that stands between you and ordering food on the evening everything overruns.</p>
  <h3>How it keeps</h3>
  <dl class="keeps">
    <div><dt>Refrigerated</dt><dd>4 days</dd></div>
    <div><dt>Frozen</dt><dd>3 months</dd></div>
    <div><dt>Best on</dt><dd>Day 2</dd></div>
  </dl>
  <h3>Storage in full</h3>
  <p>Four days refrigerated and better on day two. Freezes for three months in portions; it thickens considerably when frozen and thawed, so reheat with a splash of water. Reheat until piping hot throughout.</p>
  <h3>What to swap</h3>
  <p>Butternut squash or carrot instead of sweet potato. Brown lentils instead of red, though they hold their shape and you lose the thickening. A tin of chickpeas added at the end for more texture.</p>
