        <h2 class="mt6">Method</h2>
        <ol class="method">
      <li><div><p>Heat the oil in a large pot and cook the onion over medium heat for eight minutes until soft and translucent.</p></div></li>
      <li><div><p>Add the garlic and ginger and cook for one minute, then the cumin, coriander, paprika and cinnamon. Stir for thirty seconds only; ground spices scorch quickly.</p></div></li>
      <li><div><p>Add the tomato paste and fry it for two minutes, stirring, until it darkens from bright red to brick. This removes the raw canned edge and is worth the two minutes.</p></div></li>
      <li><div><p>Add the sweet potato, lentils, stock, chopped tomatoes and salt. Stir well and scrape the bottom of the pot.</p></div></li>
      <li><div><p>Bring to a simmer and cook, partly covered, for thirty to thirty-five minutes. Stir every ten minutes and scrape the base, because red lentils will catch and burn if left.</p></div></li>
      <li><div><p>It is ready when the lentils have completely collapsed and the sweet potato is soft enough to crush against the side of the pot with a spoon. The stew should be thick enough that a spoon stands up briefly.</p></div></li>
      <li><div><p>Take it off the heat. Add the lemon juice and taste. It will want more salt than you expect and the lemon is what lifts the whole thing out of heaviness; do not skip it.</p></div></li>
      <li><div><p>Stir through most of the herbs. Serve with yogurt, bread or rice, and the rest of the herbs on top.</p></div></li>
        </ol>

