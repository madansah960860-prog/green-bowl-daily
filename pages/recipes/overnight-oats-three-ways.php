        <div class="ingredients">
          <h2>Ingredients</h2>
    <h3>The base, per jar</h3>
    <ul>
      <li><span class="qty">50 g<small>1/2 cup</small></span><span>rolled oats</span></li>
      <li><span class="qty">150 ml<small>2/3 cup</small></span><span>milk of any kind</span></li>
      <li><span class="qty">8 g<small>1 tbsp</small></span><span>chia seeds</span></li>
      <li><span class="qty">1 pinch</span><span>fine salt</span></li>
      <li><span class="qty">1 tsp</span><span>maple syrup, optional</span></li>
    </ul>
    <h3>One: apple and cinnamon</h3>
    <ul>
      <li><span class="qty">1/2</span><span>apple, grated, skin on</span></li>
      <li><span class="qty">1/4 tsp</span><span>ground cinnamon</span></li>
      <li><span class="qty">1 tbsp</span><span>chopped walnuts, added on the morning</span></li>
    </ul>
    <h3>Two: peanut butter and banana</h3>
    <ul>
      <li><span class="qty">1 tbsp</span><span>peanut butter, stirred into the milk first</span></li>
      <li><span class="qty">1/2</span><span>banana, sliced on the morning</span></li>
      <li><span class="qty">1 tsp</span><span>cocoa nibs</span></li>
    </ul>
    <h3>Three: berry and cardamom</h3>
    <ul>
      <li><span class="qty">80 g<small>1/2 cup</small></span><span>frozen berries, added frozen</span></li>
      <li><span class="qty">1 pinch</span><span>ground cardamom</span></li>
      <li><span class="qty">1 tbsp</span><span>plain yogurt, on the morning</span></li>
    </ul>
        </div>

        <h2 class="mt6">Method</h2>
        <ol class="method">
      <li><div><p>Line up five jars. Any jar with a lid works; 350 ml is a comfortable size and leaves room to stir.</p></div></li>
      <li><div><p>Into each: the oats, chia, salt and maple syrup if using. Give them a dry stir so the chia is distributed, which stops it clumping into a single gelatinous lump overnight.</p></div></li>
      <li><div><p>Pour in the milk and stir properly, scraping the bottom. Thirty seconds of stirring now is the difference between smooth oats and a dry layer at the base.</p></div></li>
      <li><div><p>Add the flavoring for whichever version you are making. Grated apple and frozen berries go in now; peanut butter is easier if you whisk it into the milk before it goes in.</p></div></li>
      <li><div><p>Lid on, refrigerate, and leave at least six hours. Overnight is the point.</p></div></li>
      <li><div><p>In the morning, stir once and add the fresh elements: nuts, sliced banana, yogurt. These go on at the last minute because nuts go soft and banana goes brown.</p></div></li>
      <li><div><p>If it is too thick, which it will be by day three, stir in a splash of milk. The chia keeps absorbing liquid the whole time it sits.</p></div></li>
        </ol>

        <h2 class="mt6">Allergens</h2>
        <div class="note">
          <p>Contains oats, which are frequently processed alongside wheat; buy certified gluten-free oats if that matters. Contains milk unless you use a plant milk. Version one contains walnuts and version two contains peanuts. Check your plant milk, as many contain soy or nuts.</p>
          <p><strong>Read every label yourself.</strong> This note describes the ingredients as
            written here, not the packets in your kitchen, and formulations change without
            notice.</p>
        </div>

