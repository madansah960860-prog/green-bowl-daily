<aside class="prep">
  <h2>Meal prep</h2>
  <h3>Batch on Sunday</h3>
  <p>Five jars at once on Sunday evening. They are best between day one and day four; by day five the texture is noticeably heavier, which is why the batch is five and not seven.</p>
  <h3>How it keeps</h3>
  <dl class="keeps">
    <div><dt>In the jar</dt><dd>4 days</dd></div>
    <div><dt>Base only</dt><dd>5 days</dd></div>
    <div><dt>With fruit</dt><dd>2 days</dd></div>
  </dl>
  <h3>Storage in full</h3>
  <p>Four days in the jar, and the texture heaviness by day five is why the batch is five. Base without fruit keeps five days. Anything with fresh banana or berries stirred in keeps two. Do not freeze.</p>
  <h3>What to swap</h3>
  <p>Any milk, dairy or not. Any seed: chia, ground flax, or basil seeds. Rolled oats only, though; steel-cut stay hard and instant turns to paste.</p>
