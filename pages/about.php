<section class="band band--tight">
  <div class="wrap">
    <div class="prose">
      <p>I worked twelve-hour shifts as a veterinary nurse for six years, four days on and
        three off, with the on days starting at six in the morning. Cooking anything at the end
        of one of those was not going to happen, and for about two years it did not.</p>
      <p>What I ended up doing, badly at first, was cooking a great deal on the third off-day
        and eating it through the block. That works, and the thing nobody tells you is that it
        only works if you know what actually survives. I threw away a lot of food in the first
        year because a recipe said it kept for five days and it did not.</p>

      <h2>So I started checking</h2>
      <p>Properly, and a bit obsessively. Every component gets made, portioned, refrigerated,
        and then tasted on each subsequent day until it stops being good. I write down what
        changed: texture first, usually, then smell, then anything else.</p>
      <p>Where a thing was no longer good on day four, the page says three. The sesame slaw
        genuinely improves for three days and then declines, which is unusual and is stated on
        its page. The peanut sauce is better at day four than at day one. Cooked noodles are
        unpleasant by the next morning, which is why the noodle bowl tells you to cook them
        fresh even though every other component is batched.</p>
      <p>None of that is science and I would not call it that. It is one person with a
        notebook, one refrigerator and reasonably consistent conditions. It is still more than
        most recipe sites do, which is the uncomfortable part.</p>

      <h2>Why six recipes</h2>
      <p>Because six components, used properly, cover a week, and because testing keeping times
        this way takes about three weeks per recipe.</p>
      <p>A site with four hundred bowl recipes is not more useful than a site with six. It is
        less useful, because the actual problem is not a shortage of ideas. It is knowing which
        five things to make on Sunday.</p>

      <h2>What this site will not say</h2>
      <p>Clean eating. Guilt-free. Detox. Reset. Superfood. Every one of those is a marketing
        word and two of them are insults arranged to look like encouragement.</p>
      <p>Nothing here will improve your gut health, boost your immune system, or balance
        anything. The food is mostly plants because that is how I like to eat, it keeps well
        because that was the design constraint, and it tastes good because otherwise there
        would be no point. Those are the claims, and they are the whole list.</p>
      <p>I am not a dietitian and nothing here is nutritional advice. The nutrition figures on
        each recipe are database estimates, which the
        <a href="../policies/disclaimer.php">disclaimer</a> explains at some length.</p>

      <h2 id="photographs">A note on the photographs</h2>
      <p>They are licensed stock, not pictures of my food. No caption on this site implies
        otherwise, and every image is listed with its source and license in
        <code>assets/images/CREDITS.txt</code>.</p>
      <p>I am a reasonable cook and a poor photographer, and the apartment gets good light for
        about forty minutes a day. I would rather have honest keeping times and borrowed
        pictures than the other way round.</p>

      <h2>How the site is paid for</h2>
      <p>Display advertising, in the slots marked "Advertisement", and nothing else. No
        sponsored recipes, no affiliate links, no supplement company has ever been mentioned
        here and none ever will be. The
        <a href="../policies/advertising-disclosure.php">advertising disclosure</a>
        sets it out in full.</p>
    </div>
