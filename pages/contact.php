        <h2 class="mt6">What makes a keeping-time report useful</h2>
        <p>Three things. Which component, which day it went off, and what changed first. Almost
          always it is texture before smell, and knowing which one tells me whether the issue is
          moisture, temperature or the container.</p>
        <p>If several people report the same thing, the number on the page comes down and a
          dated line goes at the foot of the recipe explaining why. That has happened twice: the
          roasted chickpeas went from five days to four, and the grain bowl assembly note now
          says to keep the avocado out, which it originally did not.</p>

        <h2 class="mt6">What I cannot help with</h2>
        <p>Anything dietary or medical. I am a cook, not a dietitian, and the nutrition figures
          here are estimates. If you are managing a condition, a registered dietitian is the
          right person and the <a href="../policies/disclaimer.php">disclaimer</a>
          says so more formally.</p>
        <p>Substitutions I have not tested for keeping time. I can guess how something will
          taste; I genuinely cannot guess how long it will last, and that is the whole point of
          this site.</p>
        <p>Whether a recipe is suitable for a specific allergy. The allergen note on each page
          describes the ingredients as written. Your packets are the authority and you should
          read them.</p>

