        <h2>A Sunday that takes ninety minutes</h2>
        <p>This is the actual order, and it works because things overlap rather than queue.</p>
        <ol>
          <li><strong>Oven on, chickpeas in.</strong> Thirty-five minutes, unattended.</li>
          <li><strong>Grain on the stovetop.</strong> Also unattended. Spread it on a tray to
            cool fast when it is done, rather than leaving it in the pot.</li>
          <li><strong>Blend the two sauces</strong> while both of those run. Peanut, then
            lemon tahini. Four minutes, one jug, rinsed in between.</li>
          <li><strong>Shred the slaw and dress it.</strong> Twenty minutes and it improves for
            the next three days.</li>
          <li><strong>Stew last</strong>, in the biggest pot, while you put everything else
            away. Forty minutes, and four portions go in the freezer.</li>
        </ol>
        <p>At the end of it: two sauces, a tray of chickpeas, a pot of grain, a slaw and six
          portions of stew. That is four dinners and five breakfasts if you also made the oats
          the night before.</p>
      </div>
      <div>
        <h2>Cooling things properly</h2>
        <p>This is the unglamorous part and it is the part that decides whether food keeps for
          four days or two.</p>
        <p><strong>Cool fast, not slowly.</strong> Spread hot grain or stew on a tray rather
          than leaving it in a deep pot, where the middle stays warm for hours. Aim to get
          everything below 40&#176;F within an hour or two.</p>
        <p><strong>Cooked rice and grains deserve particular care.</strong> Spores that survive
          cooking multiply in grain left at room temperature, so cool it quickly, refrigerate it
          within an hour, and reheat it only once, until piping hot.</p>
        <p><strong>Store wet and dry separately.</strong> Dressed slaw is the exception, because
          cabbage is robust. Everything else keeps far better if the sauce is in its own jar.</p>
        <p><a href="pages/categories.php">The full meal prep page, including what freezes</a></p>
