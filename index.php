        <p class="tag">The idea</p>
        <h2>Keeping time is the number that matters</h2>
        <p>Most plant-based recipe sites tell you how long something takes to cook. Almost
          none tell you how long it lasts, which is the number that decides whether it fits
          into an actual week.</p>
        <p>So every recipe here leads with it. The peanut sauce keeps a fortnight. The slaw is
          better on day three. The greens base freezes and the eggs do not. Those four facts
          are worth more than any amount of cooking technique if you are trying to eat
          properly on a Wednesday.</p>
        <p>Every keeping time on this site was established by storing the food and eating it on
          each of the days claimed. Where something was no longer good on day four, the page
          says three.</p>
      </div>
      <div class="tile tile--soft b3">
        <p class="tag">The five slots</p>
        <h2>Every bowl, in the same five parts</h2>
        <p>Grain. Something roasted. Something raw. A sauce. Something crunchy.</p>
        <p>Most disappointing bowls are missing the last two. A sauce turns separate
          ingredients into a dish, and a handful of toasted seeds is the difference between
          eating something and enduring it.</p>
      </div>
      <div class="tile tile--apricot b3">
        <p class="tag">What this is not</p>
        <h2>No cleanses, no detox, no guilt</h2>
        <p>Nothing on this site is described as clean, guilt-free or a reset. Those are
          marketing words and two of them are insults dressed as encouragement.</p>
        <p>This is food that is mostly plants, keeps well, and is worth eating. That is the
          whole proposition and it does not need a health claim behind it.</p>
